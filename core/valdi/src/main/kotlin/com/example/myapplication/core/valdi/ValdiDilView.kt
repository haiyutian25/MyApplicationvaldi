package com.example.myapplication.core.valdi

import android.content.Context
import android.view.View
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.runtime.Composable
import androidx.compose.runtime.key
import androidx.compose.runtime.rememberUpdatedState
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.viewinterop.AndroidView
import com.snap.valdi.modules.myapp_dil.App
import com.snap.valdi.modules.myapp_dil.AppContext
import com.snap.valdi.modules.myapp_dil.AppViewModel
import timber.log.Timber

/**
 * Hosts the Valdi root component (`App` in the `myapp_dil` module) inside Compose.
 *
 * [documentJson] is the `model_dil_v2` document to render; passing a different value
 * recreates the underlying native view. [onDilAction] receives `button` taps coming
 * from the rendered document (the TS `AppContext.onDILAction` callback).
 */
@Composable
fun ValdiDilView(
    documentJson: String?,
    modifier: Modifier = Modifier,
    onDilAction: ((String) -> Unit)? = null,
) {
    val context = LocalContext.current
    val latestOnDilAction = rememberUpdatedState(onDilAction)

    key(documentJson) {
        AndroidView(
            modifier = modifier.fillMaxSize(),
            factory = {
                ValdiRootViewFactory.create(context, documentJson) { action ->
                    latestOnDilAction.value?.invoke(action)
                }
            },
        )
    }
}

/**
 * Creates the generated Valdi root view.
 *
 * `App`, `AppViewModel` and `AppContext` are generated by `valdi export android` and are
 * visible here through the exported AAR, which this module consumes as a `compileOnly`
 * dependency (see build.gradle.kts); the `:app` module ships it at runtime.
 *
 * They are referenced directly on purpose: an earlier reflective version kept compiling
 * against a renamed or reshaped generated class and then failed on the device, while a
 * direct reference turns that into a compile error.
 */
internal object ValdiRootViewFactory {

    fun create(context: Context, documentJson: String?, onAction: (String) -> Unit): View {
        val runtime = ValdiRuntimeProvider.runtime(context)
        // An empty document makes the component fall back to its built-in sample document.
        val viewModel = AppViewModel(documentJson ?: "")
        val componentContext = AppContext { action -> onAction(action) }
        val view = App.create(runtime, viewModel, componentContext, null, null)
        Timber.i("Valdi root view created: %s", view.javaClass.name)
        return view
    }
}
