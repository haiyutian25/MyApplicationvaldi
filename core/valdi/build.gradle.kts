import com.android.build.api.dsl.LibraryExtension
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    alias(libs.plugins.android.library)
    alias(libs.plugins.kotlin.compose.compiler)
}

configure<LibraryExtension> {
    namespace = "com.example.myapplication.core.valdi"
    compileSdk {
        version = release(libs.versions.compileSdk.get().toInt())
    }

    defaultConfig {
        minSdk {
            version = release(libs.versions.minSdk.get().toInt())
        }
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        consumerProguardFiles("consumer-rules.pro")
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }
    compileOptions {
        sourceCompatibility(libs.versions.jvmTarget.get())
        targetCompatibility(libs.versions.jvmTarget.get())
    }
    buildFeatures {
        compose = true
    }
    // The exported Valdi library is generated by:
    //   valdi export android --output_path my_application_valdi_export.aar
    // and is expected at core/valdi/libs/my_application_valdi_export.aar.
    // It is self contained: Valdi runtime + compiled `myapp_dil` module +
    // generated classes. See core/valdi/libs/README.md.
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.fromTarget(libs.versions.jvmTarget.get()))
    }
}

dependencies {
    // compileOnly, not implementation: a library module cannot package a local .aar
    // ("Direct local .aar file dependencies are not supported when building an AAR").
    // The :app module adds the same file as an implementation dependency, which is
    // what actually ships the Valdi runtime + generated classes. See libs/README.md.
    compileOnly(files("libs/my_application_valdi_export.aar"))

    implementation(libs.androidx.core.ktx)
    implementation(libs.androidx.appcompat)
    implementation(platform(libs.androidx.compose.bom))
    // fillMaxSize() lives in compose-foundation (version comes from the BOM above).
    implementation("androidx.compose.foundation:foundation")
    implementation(libs.androidx.compose.runtime)
    implementation(libs.androidx.compose.ui)
    implementation(libs.timber)

    testImplementation(libs.junit.jupiter)
}
